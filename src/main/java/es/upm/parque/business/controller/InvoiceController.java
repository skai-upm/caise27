package es.upm.parque.business.controller;

import es.upm.parque.business.ParkException;
import es.upm.parque.business.invoice.Invoice;
import es.upm.parque.business.invoice.InvoiceBuilder;
import es.upm.parque.business.model.Group;
import es.upm.parque.business.model.Pass;
import es.upm.parque.business.model.User;

import java.util.List;
import java.util.function.Supplier;

/**
 * Generates invoices on demand (Singleton). It directs an injected {@link InvoiceBuilder}
 * through the steps that apply to each kind of recipient. Invoices are not stored.
 */
public final class InvoiceController {

    public static final String USER_RECIPIENT = "USER";
    public static final String GROUP_RECIPIENT = "GROUP";

    private static final InvoiceController INSTANCE = new InvoiceController();

    private UserController users;
    private GroupController groups;
    private TicketController tickets;
    private PassController passes;
    private Supplier<InvoiceBuilder> builders;

    private InvoiceController() {
    }

    public static InvoiceController getInstance() {
        return INSTANCE;
    }

    public void configure(UserController users, GroupController groups, TicketController tickets,
                          PassController passes, Supplier<InvoiceBuilder> builders) {
        this.users = users;
        this.groups = groups;
        this.tickets = tickets;
        this.passes = passes;
        this.builders = builders;
    }

    public Invoice create(String recipientType, String recipient) {
        return switch (recipientType.trim().toUpperCase()) {
            case USER_RECIPIENT -> userInvoice(recipient);
            case GROUP_RECIPIENT -> groupInvoice(recipient);
            default -> throw new ParkException("invoice recipient type must be USER or GROUP, not " + recipientType);
        };
    }

    /**
     * Direct individual tickets and the personal passes of every ticket of the user
     * (including tickets generated by group tickets).
     */
    public Invoice userInvoice(String email) {
        User user = users.getByEmail(email);
        List<Pass> userPasses = passes.getPasses().stream()
                .filter(pass -> pass.getTicket().getUser() == user)
                .toList();
        return builders.get()
                .start("USER " + user.getName() + " " + user.getSurnames() + " (" + user.getEmail() + ")")
                .addIndividualTickets(tickets.directTicketsOf(user))
                .addPasses(userPasses)
                .build();
    }

    /**
     * Group ticket purchases only; their member tickets and passes are not billed again.
     */
    public Invoice groupInvoice(String groupId) {
        Group group = groups.get(groupId);
        return builders.get()
                .start("GROUP " + group.getId() + " " + group.getName())
                .addGroupTickets(tickets.groupTicketsOf(group))
                .build();
    }
}
