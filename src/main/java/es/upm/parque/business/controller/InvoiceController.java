package es.upm.parque.business.controller;

import es.upm.parque.business.invoice.Invoice;
import es.upm.parque.business.invoice.InvoiceBuilder;
import es.upm.parque.business.model.Group;
import es.upm.parque.business.model.GroupTicket;
import es.upm.parque.business.model.IndividualTicket;
import es.upm.parque.business.model.Pass;
import es.upm.parque.business.model.Ticket;
import es.upm.parque.business.model.User;

import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;
import java.util.function.Supplier;

/**
 * Directs the construction of user and group invoices with an {@link InvoiceBuilder}, adding only the
 * sections that apply to the recipient and have data.
 * Single instance (Singleton); its dependencies are injected with {@code configure} at startup.
 */
public class InvoiceController {

    private static final InvoiceController INSTANCE = new InvoiceController();

    private TicketController ticketController;
    private Supplier<InvoiceBuilder> builderFactory;

    private InvoiceController() {
    }

    public static InvoiceController getInstance() {
        return INSTANCE;
    }

    /**
     * Injects the ticket controller and the factory of builders used for each invoice.
     */
    public void configure(TicketController ticketController, Supplier<InvoiceBuilder> builderFactory) {
        this.ticketController = ticketController;
        this.builderFactory = builderFactory;
    }

    /**
     * Invoice with the user's directly bought individual tickets and the personal passes on any of the
     * user's individual tickets (including those generated by group tickets, which are not counted again).
     */
    public Invoice createUserInvoice(User user, LocalDate issueDate) {
        List<IndividualTicket> direct = new ArrayList<>();
        List<IndividualTicket> withPasses = new ArrayList<>();
        for (IndividualTicket t : ticketController.allIndividualTickets()) {
            if (t.getUser() != user) {
                continue;
            }
            if (t.getGroupTicket() == null) {
                direct.add(t);
            }
            if (!t.getPasses().isEmpty()) {
                withPasses.add(t);
            }
        }
        InvoiceBuilder builder = builderFactory.get();
        builder.reset();
        builder.setRecipient("USER " + user.getName() + " " + user.getSurname() + " (" + user.getEmail() + ")");
        builder.setIssueDate(issueDate);
        if (!direct.isEmpty()) {
            builder.startSection("Individual tickets");
            for (IndividualTicket t : direct) {
                builder.addItem("Ticket " + t.getId() + " (" + t.getDate() + ")", t.getPrice());
            }
        }
        if (!withPasses.isEmpty()) {
            builder.startSection("Personal passes");
            for (IndividualTicket t : withPasses) {
                for (Pass p : t.getPasses()) {
                    builder.addItem(p.getKind() + " " + p.getId() + " (ticket " + t.getId()
                            + (p.isConsumed() ? ", used" : "") + ")", p.getPrice());
                }
            }
        }
        return builder.getResult();
    }

    /**
     * Invoice with the group's group-ticket purchases only.
     */
    public Invoice createGroupInvoice(Group group, LocalDate issueDate) {
        List<GroupTicket> purchases = new ArrayList<>();
        for (Ticket t : ticketController.getTickets()) {
            if (t instanceof GroupTicket gt && gt.getGroup() == group) {
                purchases.add(gt);
            }
        }
        InvoiceBuilder builder = builderFactory.get();
        builder.reset();
        builder.setRecipient("GROUP " + group.getId() + " " + group.getName());
        builder.setIssueDate(issueDate);
        if (!purchases.isEmpty()) {
            builder.startSection("Group tickets");
            for (GroupTicket gt : purchases) {
                builder.addItem("Group ticket " + gt.getId() + " (" + gt.getDate() + ", "
                        + gt.getTickets().size() + " members)", gt.getPrice());
            }
        }
        return builder.getResult();
    }
}
