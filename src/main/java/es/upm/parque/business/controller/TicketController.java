package es.upm.parque.business.controller;

import es.upm.parque.business.ParkException;
import es.upm.parque.business.model.Group;
import es.upm.parque.business.model.GroupTicket;
import es.upm.parque.business.model.IndividualTicket;
import es.upm.parque.business.model.Ticket;
import es.upm.parque.business.model.User;
import es.upm.parque.business.repository.TicketRepository;
import es.upm.parque.business.validation.UserValidator;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.stream.Stream;

/**
 * Keeps individual tickets (bought directly or generated by group tickets) and group tickets
 * (Singleton). All date rules use the system date of the {@link ParkController}.
 */
public final class TicketController {

    private static final TicketController INSTANCE = new TicketController();

    private final List<IndividualTicket> individualTickets = new ArrayList<>();
    private final List<GroupTicket> groupTickets = new ArrayList<>();
    private TicketRepository repository;
    private UserController users;
    private GroupController groups;
    private PassController passes;
    private ParkController park;

    private TicketController() {
    }

    public static TicketController getInstance() {
        return INSTANCE;
    }

    public void configure(TicketRepository repository, UserController users, GroupController groups,
                          PassController passes, ParkController park) {
        this.repository = repository;
        this.users = users;
        this.groups = groups;
        this.passes = passes;
        this.park = park;
    }

    public void load() {
        TicketRepository.Loaded loaded = repository.load(users::findByDni, groups::find);
        individualTickets.clear();
        individualTickets.addAll(loaded.individualTickets());
        groupTickets.clear();
        groupTickets.addAll(loaded.groupTickets());
    }

    public List<IndividualTicket> getIndividualTickets() {
        return Collections.unmodifiableList(individualTickets);
    }

    public List<GroupTicket> getGroupTickets() {
        return Collections.unmodifiableList(groupTickets);
    }

    public Ticket find(String id) {
        return Stream.concat(individualTickets.stream(), groupTickets.stream())
                .filter(ticket -> ticket.getId().equals(id))
                .findFirst().orElse(null);
    }

    public Ticket get(String id) {
        Ticket ticket = find(id);
        if (ticket == null) {
            throw new ParkException("ticket " + id + " does not exist");
        }
        return ticket;
    }

    public IndividualTicket findIndividual(String id) {
        return individualTickets.stream().filter(ticket -> ticket.getId().equals(id)).findFirst().orElse(null);
    }

    public boolean isInGroupTicket(IndividualTicket ticket) {
        return groupTickets.stream().anyMatch(groupTicket -> groupTicket.contains(ticket));
    }

    public boolean hasActiveTicket(User user) {
        LocalDate today = park.getCurrentDate();
        return individualTickets.stream()
                .anyMatch(ticket -> ticket.getUser() == user && ticket.isActiveOn(today));
    }

    public boolean hasActiveGroupTicket(Group group) {
        LocalDate today = park.getCurrentDate();
        return groupTickets.stream()
                .anyMatch(ticket -> ticket.getGroup() == group && ticket.isActiveOn(today));
    }

    /**
     * Individual tickets of the user that were bought directly (not generated by a group ticket).
     */
    public List<IndividualTicket> directTicketsOf(User user) {
        return individualTickets.stream()
                .filter(ticket -> ticket.getUser() == user && !isInGroupTicket(ticket))
                .toList();
    }

    public List<GroupTicket> groupTicketsOf(Group group) {
        return groupTickets.stream().filter(ticket -> ticket.getGroup() == group).toList();
    }

    public IndividualTicket createTicket(String id, String email, String dateText) {
        User user = users.getByEmail(email);
        LocalDate date = purchasableDate(dateText);
        requireValidId(id);
        requireUnusedId(id);
        IndividualTicket ticket = new IndividualTicket(id, user, date, park.getTicketPrice());
        individualTickets.add(ticket);
        save();
        return ticket;
    }

    /**
     * Deletes a future individual ticket that is not part of a group ticket, together with its passes.
     */
    public void deleteTicket(String id) {
        if (!(get(id) instanceof IndividualTicket ticket)) {
            throw new ParkException(id + " is a group ticket; use GROUPTICKET DELETE");
        }
        if (isInGroupTicket(ticket)) {
            throw new ParkException("ticket " + id + " belongs to a group ticket; use GROUPTICKET DELETE");
        }
        requireFuture(ticket);
        passes.deleteForTickets(List.of(ticket));
        individualTickets.remove(ticket);
        save();
    }

    /**
     * Buys a group ticket: one individual ticket per current member at the current price,
     * and a total discounted by group size.
     */
    public GroupTicket createGroupTicket(String id, String groupId, String dateText) {
        Group group = groups.get(groupId);
        LocalDate date = purchasableDate(dateText);
        requireValidId(id);
        List<User> members = group.getMembers();
        if (members.isEmpty()) {
            throw new ParkException("group " + group.getId() + " has no members");
        }
        requireUnusedId(id);
        BigDecimal unitPrice = park.getTicketPrice();
        List<IndividualTicket> generated = new ArrayList<>();
        for (int i = 0; i < members.size(); i++) {
            String ticketId = id + "-" + (i + 1);
            requireUnusedId(ticketId);
            generated.add(new IndividualTicket(ticketId, members.get(i), date, unitPrice));
        }
        BigDecimal sum = unitPrice.multiply(BigDecimal.valueOf(members.size()));
        BigDecimal total = sum.subtract(sum.multiply(GroupTicket.discountFor(members.size())))
                .setScale(2, RoundingMode.HALF_UP);
        GroupTicket groupTicket = new GroupTicket(id, group, date, total, generated);
        individualTickets.addAll(generated);
        groupTickets.add(groupTicket);
        save();
        return groupTicket;
    }

    /**
     * Deletes a future group ticket: first the passes of its tickets, then those tickets, then itself.
     */
    public void deleteGroupTicket(String id) {
        if (!(get(id) instanceof GroupTicket groupTicket)) {
            throw new ParkException(id + " is not a group ticket; use TICKET DELETE");
        }
        requireFuture(groupTicket);
        passes.deleteForTickets(groupTicket.getTickets());
        individualTickets.removeAll(groupTicket.getTickets());
        groupTickets.remove(groupTicket);
        save();
    }

    private LocalDate purchasableDate(String text) {
        LocalDate date = ParkController.parseDate(text);
        if (date.isBefore(park.getCurrentDate())) {
            throw new ParkException("date " + date + " is before the current date " + park.getCurrentDate());
        }
        return date;
    }

    private void requireFuture(Ticket ticket) {
        if (!ticket.isFutureOn(park.getCurrentDate())) {
            throw new ParkException("ticket " + ticket.getId() + " can only be deleted before its date ("
                    + ticket.getDate() + "); current date is " + park.getCurrentDate());
        }
    }

    private void requireUnusedId(String id) {
        if (find(id) != null) {
            throw new ParkException("ticket " + id + " already exists");
        }
    }

    private static void requireValidId(String id) {
        if (!UserValidator.isNotBlank(id) || id.contains(",")) {
            throw new ParkException("ticket identifier must not be empty or contain ','");
        }
    }

    private void save() {
        repository.saveAll(individualTickets, groupTickets);
    }
}
