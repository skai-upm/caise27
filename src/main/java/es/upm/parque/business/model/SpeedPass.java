package es.upm.parque.business.model;

import java.math.BigDecimal;
import java.math.RoundingMode;

/**
 * A SpeedPass: costs 20% of the price stored in its individual ticket. A ticket may have any number of them.
 */
public class SpeedPass extends Pass {

    private static final BigDecimal RATE = new BigDecimal("0.20");

    public SpeedPass(String id, IndividualTicket ticket) {
        super(id, ticket, priceFor(ticket));
    }

    /** Reconstructs a stored SpeedPass with the price it was bought at. */
    public SpeedPass(String id, IndividualTicket ticket, BigDecimal storedPrice) {
        super(id, ticket, storedPrice);
    }

    /** Price of one SpeedPass for the ticket, from the ticket's stored (possibly discounted) price. */
    public static BigDecimal priceFor(IndividualTicket ticket) {
        return ticket.getPrice().multiply(RATE).setScale(2, RoundingMode.HALF_UP);
    }

    /** Identifier of the n-th SpeedPass generated by a purchase. */
    public static String generatedId(String purchaseId, int number) {
        return purchaseId + ":" + number;
    }

    @Override
    public String typeName() {
        return "SpeedPass";
    }
}
