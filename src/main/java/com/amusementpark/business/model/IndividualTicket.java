package com.amusementpark.business.model;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

/**
 * A ticket for one user, owning its personal passes.
 */
public class IndividualTicket extends Ticket implements IndividualAdmission {

    private final User user;
    private final List<SpeedPass> speedPasses = new ArrayList<>();
    private SpecialPass specialPass;
    private boolean specialPassPurchased;

    public IndividualTicket(String id, LocalDate date, BigDecimal price, User user) {
        this(id, date, price, user, false);
    }

    public IndividualTicket(String id, LocalDate date, BigDecimal price, User user, boolean specialPassPurchased) {
        super(id, date, price);
        this.user = user;
        this.specialPassPurchased = specialPassPurchased;
    }

    @Override
    public User getUser() {
        return user;
    }

    @Override
    public List<User> getHolders() {
        return List.of(user);
    }

    @Override
    public List<IndividualAdmission> getAdmissions() {
        return List.of(this);
    }

    public List<SpeedPass> getSpeedPasses() {
        return Collections.unmodifiableList(speedPasses);
    }

    @Override
    public SpecialPass getSpecialPass() {
        return specialPass;
    }

    /** True once a Special Pass was ever bought for this ticket, even if later consumed or refunded. */
    public boolean hasHadSpecialPass() {
        return specialPassPurchased;
    }

    /** SpeedPasses first, then the Special Pass if present. */
    public List<Pass> getPasses() {
        List<Pass> passes = new ArrayList<>(speedPasses);
        if (specialPass != null) {
            passes.add(specialPass);
        }
        return passes;
    }

    @Override
    public SpeedPass nextUnusedSpeedPass() {
        for (SpeedPass p : speedPasses) {
            if (!p.isConsumed()) {
                return p;
            }
        }
        return null;
    }

    /** Number for the next SpeedPass identifier {@code <ticketId>-S<n>}. */
    public int nextSpeedPassNumber() {
        int max = 0;
        String prefix = getId() + "-S";
        for (SpeedPass p : speedPasses) {
            try {
                max = Math.max(max, Integer.parseInt(p.getId().substring(prefix.length())));
            } catch (NumberFormatException | IndexOutOfBoundsException e) {
                // identifier not generated by this scheme; ignore
            }
        }
        return max + 1;
    }

    public void addSpeedPass(SpeedPass pass) {
        speedPasses.add(pass);
    }

    public void removeSpeedPass(SpeedPass pass) {
        speedPasses.remove(pass);
    }

    public void setSpecialPass(SpecialPass pass) {
        specialPass = pass;
        specialPassPurchased = true;
    }

    public void removeSpecialPass() {
        specialPass = null;
    }
}
