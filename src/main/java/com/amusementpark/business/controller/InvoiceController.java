package com.amusementpark.business.controller;

import com.amusementpark.business.invoice.Invoice;
import com.amusementpark.business.invoice.InvoiceBuilder;
import com.amusementpark.business.model.Group;
import com.amusementpark.business.model.GroupTicket;
import com.amusementpark.business.model.IndividualTicket;
import com.amusementpark.business.model.SpecialPass;
import com.amusementpark.business.model.SpeedPass;
import com.amusementpark.business.model.User;

import java.util.ArrayList;
import java.util.List;
import java.util.function.Supplier;

/**
 * Generates invoices on demand, directing an injected invoice builder through the steps that
 * apply to each kind of recipient.
 */
public final class InvoiceController {
    private static final InvoiceController INSTANCE = new InvoiceController();

    private UserController userController;
    private GroupController groupController;
    private TicketController ticketController;
    private Supplier<InvoiceBuilder> builders;

    private InvoiceController() {
    }

    public static InvoiceController getInstance() {
        return INSTANCE;
    }

    public void configure(Supplier<InvoiceBuilder> builders, UserController userController,
                          GroupController groupController, TicketController ticketController) {
        this.builders = builders;
        this.userController = userController;
        this.groupController = groupController;
        this.ticketController = ticketController;
    }

    /**
     * Handles {@code INVOICE CREATE;USER|GROUP;key}.
     */
    public String create(String recipientType, String key) {
        switch (recipientType) {
            case "USER":
                User user = userController.findByEmail(key);
                return user == null ? "ERROR: unknown user " + key : userInvoice(user).render();
            case "GROUP":
                Group group = groupController.findGroup(key);
                return group == null ? "ERROR: unknown group " + key : groupInvoice(group).render();
            default:
                return "ERROR: invoices are for USER or GROUP, not " + recipientType;
        }
    }

    /**
     * Tickets bought directly for the user, plus the passes of all the user's individual tickets
     * (including those generated by group tickets, which are not charged again here).
     */
    public Invoice userInvoice(User user) {
        List<IndividualTicket> direct = new ArrayList<>();
        for (IndividualTicket ticket : ticketController.getTickets()) {
            if (ticket.getUser() == user) {
                direct.add(ticket);
            }
        }
        List<SpeedPass> speedPasses = new ArrayList<>();
        List<SpecialPass> specialPasses = new ArrayList<>();
        for (IndividualTicket ticket : ticketController.allIndividualTickets()) {
            if (ticket.getUser() == user) {
                speedPasses.addAll(ticket.getSpeedPasses());
                if (ticket.getSpecialPass() != null) {
                    specialPasses.add(ticket.getSpecialPass());
                }
            }
        }
        return builders.get()
                .forRecipient("USER " + user.getEmail() + " - " + user.getName() + " " + user.getSurname())
                .addIndividualTickets(direct)
                .addSpeedPasses(speedPasses)
                .addSpecialPasses(specialPasses)
                .build();
    }

    /**
     * The group's group tickets only; member tickets and passes are not repeated.
     */
    public Invoice groupInvoice(Group group) {
        List<GroupTicket> bought = new ArrayList<>();
        for (GroupTicket groupTicket : ticketController.getGroupTickets()) {
            if (groupTicket.getGroup() == group) {
                bought.add(groupTicket);
            }
        }
        return builders.get()
                .forRecipient("GROUP " + group.getId() + " - " + group.getName())
                .addGroupTickets(bought)
                .build();
    }
}
